"""Generate the BigQuery ML version of the pipeline as three SQL scripts.

    python -m appchurn.bqml                                  # placeholders -> bigquery_ml/
    python -m appchurn.bqml --project my-project-id          # yours -> bigquery_ml/local/
    python -m appchurn.bqml --project my-project-id --bucket my-bucket \
        --events-table my-project-id.flood_it.events --score-date 2018-10-04

Production versions for scheduled queries are written to ``bigquery_ml/scheduled/``
(see ``appchurn.bqml_scheduled``). The committed scripts use placeholder names:

    01_train_model.sql      training table, CREATE MODEL, out-of-time evaluation
    02_score_users.sql      today's features, ML.PREDICT, ranked at-risk table
    03_export_at_risk.sql   EXPORT DATA to a CSV in Cloud Storage

The feature SQL is rendered from the same template the Python pipeline uses, so the
two versions cannot drift apart; a test checks the committed files are up to date.
"""

from __future__ import annotations

import argparse
import re
from dataclasses import dataclass, replace
from datetime import date, timedelta
from pathlib import Path

from appchurn.config import DATASET, PROJECT_ROOT, WINDOWS, DatasetConfig, WindowConfig
from appchurn.sql import user_snapshot_sql

OUT_DIR = PROJECT_ROOT / "bigquery_ml"
_NAME = re.compile(r"^[A-Za-z0-9_\-]+$")


@dataclass(frozen=True)
class Target:
    """Where the BigQuery ML objects live. Defaults are placeholders."""

    project: str = "your-project-id"
    dataset: str = "churn_demo"
    bucket: str = "your-bucket"
    location: str = "US"

    def __post_init__(self) -> None:
        for value in (self.project, self.dataset, self.bucket, self.location):
            if not _NAME.match(value):
                raise ValueError(f"Invalid name: {value!r}")

    def ref(self, name: str) -> str:
        return f"`{self.project}.{self.dataset}.{name}`"


DEFAULT_TARGET = Target()


def derived_features_sql(obs: int = WINDOWS.observation_days, indent: str = "  ") -> str:
    """SQL twin of features.add_derived_features (a test checks they agree)."""
    weeks = obs / 7
    lines = [
        f"SAFE_DIVIDE(events_7d, events_{obs}d / {weeks:g}) AS events_7d_vs_weekly_avg",
        "active_days_7d / 7 AS active_day_share_7d",
        f"active_days_{obs}d / {obs} AS active_day_share_obs",
        f"SAFE_DIVIDE(engagement_minutes_{obs}d, active_days_{obs}d) AS minutes_per_active_day",
        f"SAFE_DIVIDE(events_{obs}d, sessions_{obs}d) AS events_per_session",
        f"IF(revenue_usd_{obs}d > 0, 1, 0) AS is_payer",
    ]
    return (",\n" + indent).join(lines)


def _model_input_sql(
    feature_sql: str, dataset: DatasetConfig, windows: WindowConfig, extra: str = ""
) -> str:
    """Wrap the feature SQL: fix placeholder tenures, add ratios, keep regular users."""
    body = re.sub(r"\nORDER BY [^\n]+\n?$", "\n", feature_sql.rstrip() + "\n").rstrip()
    body = "\n".join("    " + line if line else line for line in body.splitlines())
    obs = windows.observation_days
    floor = dataset.earliest_valid_first_touch
    return f"""SELECT
  * REPLACE (
    -- Placeholder install dates in the obfuscated export imply tenures of decades
    IF(tenure_days > DATE_DIFF(snapshot_date, DATE '{floor:%Y-%m-%d}', DAY), NULL, tenure_days)
      AS tenure_days
  ),
  {derived_features_sql(obs)}{extra}
FROM (
{body}
)
-- regular users only
WHERE active_days_{obs}d >= {windows.min_active_days}"""


def train_sql(
    target: Target = DEFAULT_TARGET,
    dataset: DatasetConfig = DATASET,
    windows: WindowConfig = WINDOWS,
) -> str:
    churn, test_from = windows.churn_days, windows.test_from
    model, table = target.ref("app_churn_model"), target.ref("training_snapshots")
    split = f",\n  snapshot_date >= DATE '{test_from:%Y-%m-%d}' AS is_test_week"
    model_input = _model_input_sql(user_snapshot_sql(dataset, windows), dataset, windows, split)
    model_input += (
        f"\n  -- drop training weeks whose 14-day outcome overlaps the test period\n"
        f"  AND (snapshot_date >= DATE '{test_from:%Y-%m-%d}'\n"
        f"       OR DATE_ADD(snapshot_date, INTERVAL {churn} DAY) <= DATE '{test_from:%Y-%m-%d}')"
    )
    return f"""-- =====================================================================
-- 1 of 3 · Train the churn model with BigQuery ML
-- Generated by `python -m appchurn.bqml`; edit config.py, not this file.
--
-- What it does, in order:
--   a) Creates the dataset {target.project}.{target.dataset} (location {target.location}).
--   b) Builds the training table: one row per regular user per weekly snapshot,
--      with 28 days of behaviour and the 14-day churn label (1 = went silent).
--   c) Trains a boosted-tree classifier on the July-August weeks only.
--   d) Evaluates it on the September weeks it never saw (out-of-time test),
--      compare roc_auc with the Python model's 0.798.
--   e) Lists which features the model relies on most.
--
-- Run the whole script in the BigQuery console (Run runs every statement).
-- Scans about 1 GB of the public export. CREATE MODEL may need billing enabled
-- if your project is still in the free sandbox.
-- =====================================================================

-- a) Dataset for the BigQuery ML objects
CREATE SCHEMA IF NOT EXISTS `{target.project}.{target.dataset}`
OPTIONS (location = '{target.location}');

-- b) Training table: features + label for every weekly snapshot
CREATE OR REPLACE TABLE {table} AS
{model_input};

-- c) Train: boosted trees, the same model family as the Python pipeline.
--    NO_SPLIT because the test weeks are held out explicitly; early stopping off so
--    the test weeks never influence training.
CREATE OR REPLACE MODEL {model}
OPTIONS (
  model_type = 'BOOSTED_TREE_CLASSIFIER',
  input_label_cols = ['churned'],
  data_split_method = 'NO_SPLIT',
  max_iterations = 50,
  learn_rate = 0.1,
  max_tree_depth = 6,
  subsample = 0.8,
  l2_reg = 1.0,
  early_stop = FALSE,
  enable_global_explain = TRUE
) AS
SELECT * EXCEPT (user_pseudo_id, snapshot_date, is_test_week)
FROM {table}
WHERE NOT is_test_week;

-- d) Out-of-time evaluation on the September weeks
SELECT roc_auc, precision, recall, accuracy, log_loss
FROM ML.EVALUATE(
  MODEL {model},
  (SELECT * EXCEPT (user_pseudo_id, snapshot_date, is_test_week)
   FROM {table}
   WHERE is_test_week)
);

-- e) Feature importance across the training data
SELECT feature, ROUND(attribution, 4) AS attribution
FROM ML.GLOBAL_EXPLAIN(MODEL {model})
ORDER BY attribution DESC
LIMIT 15;
"""


def _reasons_sql(obs: int, journeys: tuple[str, ...] = DATASET.journey_events) -> str:
    """SQL twin of score.reason_codes: same rules, same order, up to three reasons."""
    rules = [
        "IF(days_since_last_active >= 7,\n"
        "           FORMAT('Silent %d days', days_since_last_active), NULL)",
        "IF(days_since_last_active BETWEEN 3 AND 6,\n"
        "           FORMAT('Not seen for %d days', days_since_last_active), NULL)",
        "IF(events_7d_vs_weekly_avg < 0.5 AND days_since_last_active < 7,\n"
        "           FORMAT('Activity down %d%% vs usual week',\n"
        "                  CAST(ROUND((1 - events_7d_vs_weekly_avg) * 100) AS INT64)), NULL)",
        f"IF(active_days_{obs}d <= 4,\n"
        f"           FORMAT('Only %d active days in {obs}', active_days_{obs}d), NULL)",
        "IF(tenure_days < 30, FORMAT('New user (%d days)', tenure_days), NULL)",
    ]
    if {"level_fail_quickplay", "level_start_quickplay"} <= set(journeys):
        fails, starts = f"n_level_fail_quickplay_{obs}d", f"n_level_start_quickplay_{obs}d"
        rules.append(
            f"IF({starts} >= 10 AND SAFE_DIVIDE({fails}, {starts}) >= 0.4,\n"
            f"           FORMAT('Fails often (%d%% of attempts)',\n"
            f"                  CAST(ROUND(SAFE_DIVIDE({fails}, {starts}) * 100) AS INT64)), NULL)"
        )
    errors = [f"n_{e}_{obs}d" for e in ("error", "app_exception") if e in journeys]
    if errors:
        total = " + ".join(errors)
        rules.append(f"IF({total} > 0,\n           FORMAT('Hit app errors (%d)', {total}), NULL)")
    body = ",\n        ".join(rules)
    return f"""ARRAY_TO_STRING(ARRAY(
      SELECT reason FROM UNNEST([
        {body}
      ]) AS reason WITH OFFSET AS pos
      WHERE reason IS NOT NULL
      ORDER BY pos
      LIMIT 3
    ), '; ')"""


def default_score_date(dataset: DatasetConfig = DATASET) -> date:
    """The day after the last day of data: 'today' for the demo."""
    return dataset.data_end + timedelta(days=1)


def score_sql(
    target: Target = DEFAULT_TARGET,
    dataset: DatasetConfig = DATASET,
    windows: WindowConfig = WINDOWS,
    score_date: date | None = None,
) -> str:
    score_date = score_date or default_score_date(dataset)
    obs = windows.observation_days
    model = target.ref("app_churn_model")
    features, at_risk = target.ref("scoring_features"), target.ref("at_risk_customers")
    model_input = _model_input_sql(
        user_snapshot_sql(dataset, windows, score_date=score_date), dataset, windows
    )
    return f"""-- =====================================================================
-- 2 of 3 · Score users and save the ranked at-risk list
-- Generated by `python -m appchurn.bqml`; edit config.py, not this file.
--
-- Score date: {score_date:%Y-%m-%d} (the day after the last day of data, i.e. "today").
-- Features use the {obs} days up to the day before; the outcome is unknown, which is
-- exactly the situation of a real daily job.
--
-- What it does:
--   a) Builds today's features for every regular user (same SQL as training).
--   b) Runs the model (ML.PREDICT) to get each user's probability of churning.
--   c) Ranks users, assigns bands by rank (High = riskiest 20%, Medium = next 30%,
--      Low = the rest) and adds plain-language reasons.
--
-- In production this runs daily as a scheduled query with the score date moved
-- forward (re-generate with --score-date, or use CURRENT_DATE()). Scheduled
-- queries need billing enabled; in the free sandbox run it by hand.
-- =====================================================================

-- a) Today's features
CREATE OR REPLACE TABLE {features} AS
{model_input};

-- b) and c) Predict, rank, band and explain
CREATE OR REPLACE TABLE {at_risk} AS
WITH scored AS (
  SELECT
    user_pseudo_id,
    snapshot_date AS score_date,
    (SELECT prob FROM UNNEST(predicted_churned_probs) WHERE label = 1) AS churn_probability,
    days_since_last_active,
    active_days_{obs}d,
    events_7d_vs_weekly_avg,
    tenure_days,
    * EXCEPT (user_pseudo_id, snapshot_date, days_since_last_active, active_days_{obs}d,
              events_7d_vs_weekly_avg, tenure_days, platform, country, device_category,
              predicted_churned, predicted_churned_probs),
    platform,
    country,
    device_category
  FROM ML.PREDICT(MODEL {model}, TABLE {features})
),
ranked AS (
  SELECT
    *,
    ROW_NUMBER() OVER (ORDER BY churn_probability DESC) AS risk_rank,
    PERCENT_RANK() OVER (ORDER BY churn_probability DESC) AS rank_share
  FROM scored
)
SELECT
  score_date,
  risk_rank,
  user_pseudo_id,
  CASE
    WHEN rank_share < 0.2 THEN 'High'
    WHEN rank_share < 0.5 THEN 'Medium'
    ELSE 'Low'
  END AS risk_band,
  ROUND(churn_probability, 4) AS churn_probability,
  IFNULL(NULLIF({_reasons_sql(obs, dataset.journey_events)}, ''),
         'No single strong signal') AS reasons,
  days_since_last_active,
  active_days_{obs}d,
  ROUND(events_7d_vs_weekly_avg, 2) AS events_7d_vs_weekly_avg,
  tenure_days,
  platform,
  country,
  device_category
FROM ranked;

-- Quick look: how many users per band, and the top of the list
SELECT risk_band, COUNT(*) AS users, ROUND(AVG(churn_probability), 3) AS avg_probability
FROM {at_risk}
GROUP BY risk_band
ORDER BY MIN(risk_rank);

SELECT * FROM {at_risk} ORDER BY risk_rank LIMIT 20;
"""


def export_sql(
    target: Target = DEFAULT_TARGET,
    dataset: DatasetConfig = DATASET,
    score_date: date | None = None,
) -> str:
    score_date = score_date or default_score_date(dataset)
    at_risk = target.ref("at_risk_customers")
    uri = f"gs://{target.bucket}/churn/at_risk/score_date={score_date:%Y-%m-%d}/*.csv"
    return f"""-- =====================================================================
-- 3 of 3 · Export the at-risk list as CSV for a campaign platform
-- Generated by `python -m appchurn.bqml`; edit config.py, not this file.
--
-- Writes the High and Medium bands to Cloud Storage, one folder per score date.
-- A campaign or next-best-action platform picks the file up from there (or via
-- SFTP / API, depending on how that platform is set up).
--
-- Needs: billing enabled, and a Cloud Storage bucket named {target.bucket} in the
-- same location as the dataset ({target.location}). In the free sandbox, instead run
-- the SELECT below on its own and use "Save results" > CSV in the console.
--
-- Before any real campaign: join an identity map (app user -> customer ID) and
-- filter on marketing consent and contact caps; keep a random holdout group.
-- =====================================================================

EXPORT DATA OPTIONS (
  uri = '{uri}',
  format = 'CSV',
  header = true,
  overwrite = true
) AS
SELECT
  score_date,
  risk_rank,
  user_pseudo_id,
  risk_band,
  churn_probability,
  reasons
FROM {at_risk}
WHERE risk_band IN ('High', 'Medium')
ORDER BY risk_rank;
"""


def render_all(
    target: Target = DEFAULT_TARGET,
    dataset: DatasetConfig = DATASET,
    windows: WindowConfig = WINDOWS,
    score_date: date | None = None,
) -> dict[str, str]:
    return {
        "01_train_model.sql": train_sql(target, dataset, windows),
        "02_score_users.sql": score_sql(target, dataset, windows, score_date),
        "03_export_at_risk.sql": export_sql(target, dataset, score_date),
    }


def write(files: dict[str, str], out_dir: Path = OUT_DIR) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, sql in files.items():
        path = out_dir / name
        path.write_text(sql, encoding="utf-8")
        paths.append(path)
    return paths


PUBLIC_EVENTS_TABLE = "firebase-public-project.analytics_153293282.events_*"


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the BigQuery ML SQL scripts")
    parser.add_argument("--project", default=DEFAULT_TARGET.project)
    parser.add_argument("--dataset", default=DEFAULT_TARGET.dataset)
    parser.add_argument("--bucket", default=DEFAULT_TARGET.bucket)
    parser.add_argument(
        "--events-table",
        default=PUBLIC_EVENTS_TABLE,
        help="source events table (default: Google's public Flood-It! export)",
    )
    parser.add_argument("--score-date", type=date.fromisoformat, default=None)
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args()

    target = Target(project=args.project, dataset=args.dataset, bucket=args.bucket)
    dataset = replace(DATASET, events_table=args.events_table)
    personalised = target != DEFAULT_TARGET or args.events_table != PUBLIC_EVENTS_TABLE
    # Copies with real project names go to a git-ignored folder, so they are never
    # committed by accident; the repository keeps the placeholder versions.
    out = args.out or (OUT_DIR / "local" if personalised else OUT_DIR)
    for path in write(render_all(target, dataset, score_date=args.score_date), out):
        print(f"wrote {path}")
    from appchurn import bqml_scheduled

    scheduled = bqml_scheduled.render_all(target, dataset)
    for path in write(scheduled, out / "scheduled"):
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
