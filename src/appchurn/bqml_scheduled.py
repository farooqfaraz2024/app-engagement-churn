"""Production BigQuery ML scripts, ready for BigQuery scheduled queries.

    python -m appchurn.bqml          # writes bigquery_ml/ and bigquery_ml/scheduled/

The scripts in ``bigquery_ml/scheduled/``:

    00_setup.sql             once      dataset, history tables, model registry
    01_retrain_monthly.sql   monthly   rolling training window, candidate model,
                                       promotion gate, model registry
    02_score_daily.sql       daily     data guard, active model, today's scores kept
                                       as history, stable 10% holdout
    03_export_daily.sql      daily     CSV of High/Medium users outside the holdout
    04_monitor_weekly.sql    weekly    outcomes of past scores, ROC-AUC vs the
                                       recency rule, calibration, holdout comparison

Every date comes from one variable, ``run_date``. It is set to the demo date so the
scripts run against the 2018 public data; when scheduling, change its default to
``@run_date``, the date BigQuery's scheduler passes to each run.

Statements that read the raw events are built as text and run with EXECUTE
IMMEDIATE, so their date filters reach BigQuery as constants. Google documents that
only constant filters on ``_TABLE_SUFFIX`` limit which daily tables are scanned,
which is what keeps a daily job cheap. Inside that text, ``__TOKENS__`` stand for the
run-time values; the tests replace them exactly as BigQuery's REPLACE() does and run
the result locally.
"""

from __future__ import annotations

import re
from datetime import date, timedelta

from appchurn.bqml import DEFAULT_TARGET, Target, _model_input_sql, _reasons_sql
from appchurn.config import DATASET, WINDOWS, DatasetConfig, WindowConfig
from appchurn.sql import RuntimeDates, events_source, user_snapshot_sql

HISTORY_WEEKS = 16  # weekly snapshots in each training run
TEST_WEEKS = 2  # newest labelled weeks held back for the promotion gate
HOLDOUT_PERCENT = 10  # at-risk users never contacted, to measure the campaign
HOLDOUT_SALT = "holdout-v1"  # change to reshuffle the holdout group

TOKENS = ("__SNAPSHOTS__", "__FIRST_SUFFIX__", "__LAST_SUFFIX__", "__FIRST_TEST__",
          "__MODEL__", "__DATE__", "__EARLIEST__", "__LATEST__")  # fmt: skip


def demo_run_date(dataset: DatasetConfig = DATASET) -> date:
    """The day after the last day of data: 'today' for the demo."""
    return dataset.data_end + timedelta(days=1)


def _raw(sql: str) -> str:
    if '"""' in sql:
        raise ValueError("SQL for EXECUTE IMMEDIATE must not contain triple quotes")
    return 'r"""\n' + sql.strip("\n") + '\n"""'


def execute(sql: str, replacements: list[tuple[str, str]], into: str | None = None) -> str:
    """EXECUTE IMMEDIATE of `sql` with each token replaced by a SQL string expression."""
    for token, _ in replacements:
        if token not in sql:
            raise ValueError(f"{token} does not appear in the SQL")
    leftover = [t for t in TOKENS if t in sql and t not in dict(replacements)]
    if leftover:
        raise ValueError(f"Tokens without a value: {leftover}")
    expr = _raw(sql)
    for token, value in replacements:
        expr = f"REPLACE({expr},\n  '{token}', {value})"
    return f"EXECUTE IMMEDIATE {expr}" + (f" INTO {into};" if into else ";")


def auc_sql(label: str, score: str, partition: str | None = None) -> tuple[str, str]:
    """ROC-AUC in plain SQL (Mann-Whitney rank formula, ties get average ranks).

    Returns (rank column expression, aggregate expression). A test checks the result
    against scikit-learn.
    """
    by = f"PARTITION BY {partition} " if partition else ""
    tie_by = f"{partition}, {score}" if partition else score
    rank = f"RANK() OVER ({by}ORDER BY {score}) + (COUNT(*) OVER (PARTITION BY {tie_by}) - 1) / 2"
    pos, neg = f"COUNTIF({label} = 1)", f"COUNTIF({label} = 0)"
    agg = (
        f"(SUM(IF({label} = 1, {{rank}}, 0)) - {pos} * ({pos} + 1) / 2) / NULLIF({pos} * {neg}, 0)"
    )
    return rank, agg


RULE_SCORE = f"days_since_last_active - 0.01 * active_days_{WINDOWS.observation_days}d"


