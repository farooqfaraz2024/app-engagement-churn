def raw_blocks(script: str) -> list[str]:
    """The SQL texts inside r\"\"\"...\"\"\" blocks (used by the tests)."""
    return [m.strip("\n") for m in re.findall(r'r"""\n(.*?)\n"""', script, re.S)]
