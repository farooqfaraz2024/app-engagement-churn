def training_input_sql(dataset: DatasetConfig = DATASET, windows: WindowConfig = WINDOWS) -> str:
    """Training table SQL with run-time tokens for the snapshot list and date range."""
    runtime = RuntimeDates("__SNAPSHOTS__", "'__FIRST_SUFFIX__'", "'__LAST_SUFFIX__'", True)
    split = ",\n  snapshot_date >= DATE '__FIRST_TEST__' AS is_test_week"
    sql = _model_input_sql(user_snapshot_sql(dataset, windows, runtime=runtime),
                           dataset, windows, split)  # fmt: skip
    sql += (
        "\n  -- drop training weeks whose 14-day outcome overlaps the test period\n"
        "  AND (snapshot_date >= DATE '__FIRST_TEST__'\n"
        f"       OR DATE_ADD(snapshot_date, INTERVAL {windows.churn_days} DAY)"
        " <= DATE '__FIRST_TEST__')"
    )
    return sql


def scoring_input_sql(dataset: DatasetConfig = DATASET, windows: WindowConfig = WINDOWS) -> str:
    runtime = RuntimeDates("__SNAPSHOTS__", "'__FIRST_SUFFIX__'", "'__LAST_SUFFIX__'", False)
    return _model_input_sql(user_snapshot_sql(dataset, windows, runtime=runtime),
                            dataset, windows)  # fmt: skip


def retrain_sql(
    target: Target = DEFAULT_TARGET,
    dataset: DatasetConfig = DATASET,
    windows: WindowConfig = WINDOWS,
    run_date: date | None = None,
) -> str:
    run_date = run_date or demo_run_date(dataset)
    obs, churn = windows.observation_days, windows.churn_days
    table, registry = target.ref("training_snapshots"), target.ref("model_registry")
    model_ref = f"`{target.project}.{target.dataset}.__MODEL__`"
    features = "* EXCEPT (user_pseudo_id, snapshot_date, is_test_week)"
    rank, agg = auc_sql("churned", "rule_score")
    build = execute(
        f"CREATE OR REPLACE TABLE {table} AS\n" + training_input_sql(dataset, windows),
        [
            ("__SNAPSHOTS__", "snapshots_sql"),
            (
                "__FIRST_SUFFIX__",
                f"FORMAT_DATE('%Y%m%d', DATE_SUB(snapshots[OFFSET(0)], INTERVAL {obs} DAY))",
            ),
            ("__LAST_SUFFIX__", "FORMAT_DATE('%Y%m%d', DATE_SUB(run_date, INTERVAL 1 DAY))"),
            ("__FIRST_TEST__", "CAST(first_test AS STRING)"),
        ],
    )  # fmt: skip
    train = execute(
        f"""CREATE OR REPLACE MODEL {model_ref}
OPTIONS (
  model_type = 'BOOSTED_TREE_CLASSIFIER',
  input_label_cols = ['churned'],
  data_split_method = 'NO_SPLIT',
  max_iterations = 50,
  learn_rate = 0.1,
  max_tree_depth = 6,
  subsample = 0.8,
  l2_reg = 1.0,
  early_stop = FALSE,
  enable_global_explain = TRUE
) AS
SELECT {features}
FROM {table}
WHERE NOT is_test_week""",
        [("__MODEL__", "candidate")],
    )
    evaluate = f"""SELECT roc_auc FROM ML.EVALUATE(
  MODEL {model_ref},
  (SELECT {features} FROM {table} WHERE is_test_week)
)"""
    return (
        _header(
            1,
            "Retrain the model and promote it only if it wins",
            "monthly, e.g. 1st of the month 06:00",
            [
                "a) Builds the training table from the latest weekly snapshots whose",
                f"   {churn}-day outcome is complete (up to {HISTORY_WEEKS} weeks).",
                f"b) Trains a candidate model on all but the newest {TEST_WEEKS} weeks.",
                f"c) Scores the newest {TEST_WEEKS} weeks with the candidate, the active",
                "   model and the no-model recency rule.",
                "d) Promotion gate: the candidate becomes active only if it beats the",
                "   rule and is at least as good as the active model. Every decision is",
                "   recorded in model_registry; rejected candidates are dropped.",
                "",
                "Needs 00_setup.sql first. For the 2018 demo data run_date is the day",
                "after the data ends; see the README for a backtest walkthrough.",
            ],
        )
        + f"""
{_RUN_DATE_LINE.format(d=run_date)}
DECLARE history_start DATE DEFAULT DATE '{dataset.data_start:%Y-%m-%d}';  -- first day of event data
DECLARE last_snapshot DATE;
DECLARE snapshots ARRAY<DATE>;
DECLARE snapshots_sql STRING;
DECLARE first_test DATE;
DECLARE candidate STRING;
DECLARE current_model STRING;
DECLARE candidate_auc FLOAT64;
DECLARE current_auc FLOAT64;
DECLARE rule_auc FLOAT64;
DECLARE promote BOOL;

-- Newest snapshot whose {churn}-day outcome is complete by yesterday
SET last_snapshot = DATE_SUB(run_date, INTERVAL {churn} DAY);
SET snapshots = ARRAY(
  SELECT d
  FROM UNNEST(GENERATE_DATE_ARRAY(
    DATE_SUB(last_snapshot, INTERVAL {7 * (HISTORY_WEEKS - 1)} DAY),
    last_snapshot,
    INTERVAL 7 DAY)) AS d
  WHERE d >= DATE_ADD(history_start, INTERVAL {obs} DAY)  -- needs a full {obs}-day window
  ORDER BY d
);
IF ARRAY_LENGTH(snapshots) < {TEST_WEEKS + 3} THEN
  RAISE USING MESSAGE = 'Not enough weeks of history to train and test a model';
END IF;
SET first_test = snapshots[ORDINAL(ARRAY_LENGTH(snapshots) - {TEST_WEEKS - 1})];
SET snapshots_sql = (
  SELECT CONCAT('[', STRING_AGG(CONCAT("DATE '", CAST(d AS STRING), "'"), ', ' ORDER BY d), ']')
  FROM UNNEST(snapshots) AS d
);
SET candidate = CONCAT('app_churn_model_', FORMAT_DATE('%Y%m%d', run_date));

-- a) Training table (only the daily tables in the window are read)
{build}

-- b) Candidate model
{train}

-- c) Score the test weeks: candidate, active model, recency rule
{execute(evaluate, [("__MODEL__", "candidate")], into="candidate_auc")}

SET current_model = (SELECT model_name FROM {registry} WHERE is_active LIMIT 1);
IF current_model IS NOT NULL THEN
  {execute(evaluate, [("__MODEL__", "current_model")], into="current_auc")}
END IF;

SET rule_auc = (
  WITH scored AS (
    SELECT churned, {RULE_SCORE} AS rule_score
    FROM {table}
    WHERE is_test_week
  ),
  ranked AS (SELECT churned, {rank} AS r FROM scored)
  SELECT {agg.format(rank="r")} FROM ranked
);

-- d) Promotion gate
SET promote = candidate_auc > rule_auc AND (current_auc IS NULL OR candidate_auc >= current_auc);

INSERT INTO {registry}
SELECT
  candidate, CURRENT_TIMESTAMP(), run_date,
  snapshots[OFFSET(0)], DATE_SUB(first_test, INTERVAL {churn} DAY), first_test, last_snapshot,
  candidate_auc, current_model, current_auc, rule_auc, FALSE,
  CASE
    WHEN promote THEN 'promoted'
    WHEN candidate_auc <= rule_auc THEN 'rejected: not better than the recency rule'
    ELSE 'rejected: worse than the active model'
  END;

IF promote THEN
  UPDATE {registry} SET is_active = (model_name = candidate) WHERE TRUE;
ELSE
  {execute("DROP MODEL IF EXISTS " + model_ref, [("__MODEL__", "candidate")])}
END IF;

SELECT model_name, run_date, candidate_roc_auc, previous_active_roc_auc, rule_roc_auc,
       is_active, decision
FROM {registry}
ORDER BY trained_at DESC
LIMIT 5;
"""
    )


def score_daily_sql(
    target: Target = DEFAULT_TARGET,
    dataset: DatasetConfig = DATASET,
    windows: WindowConfig = WINDOWS,
    run_date: date | None = None,
) -> str:
    run_date = run_date or demo_run_date(dataset)
    obs = windows.observation_days
    features, at_risk = target.ref("scoring_features"), target.ref("at_risk_customers")
    registry = target.ref("model_registry")
    guard = execute(
        "SELECT COUNT(*) FROM "
        + events_source(dataset, bounds_sql=("'__FIRST_SUFFIX__'", "'__LAST_SUFFIX__'")),
        [
            ("__FIRST_SUFFIX__", "FORMAT_DATE('%Y%m%d', DATE_SUB(run_date, INTERVAL 1 DAY))"),
            ("__LAST_SUFFIX__", "FORMAT_DATE('%Y%m%d', DATE_SUB(run_date, INTERVAL 1 DAY))"),
        ],
        into="events_yesterday",
    )
    build = execute(
        f"CREATE OR REPLACE TABLE {features} AS\n" + scoring_input_sql(dataset, windows),
        [
            ("__SNAPSHOTS__", """CONCAT("[DATE '", CAST(run_date AS STRING), "']")"""),
            ("__FIRST_SUFFIX__", f"FORMAT_DATE('%Y%m%d', DATE_SUB(run_date, INTERVAL {obs} DAY))"),
            ("__LAST_SUFFIX__", "FORMAT_DATE('%Y%m%d', DATE_SUB(run_date, INTERVAL 1 DAY))"),
        ],
    )  # fmt: skip
    model_ref = f"`{target.project}.{target.dataset}.__MODEL__`"
    insert = execute(
        f"""INSERT INTO {at_risk} (
  score_date, risk_rank, user_pseudo_id, risk_band, churn_probability, reasons,
  in_holdout, model_name, days_since_last_active, active_days_{obs}d,
  events_7d_vs_weekly_avg, tenure_days, platform, country, device_category
)
WITH scored AS (
  SELECT
    *,
    (SELECT prob FROM UNNEST(predicted_churned_probs) WHERE label = 1) AS churn_probability
  FROM ML.PREDICT(MODEL {model_ref}, TABLE {features})
),
ranked AS (
  SELECT
    *,
    ROW_NUMBER() OVER (ORDER BY churn_probability DESC) AS risk_rank,
    PERCENT_RANK() OVER (ORDER BY churn_probability DESC) AS rank_share
  FROM scored
)
SELECT
  snapshot_date,
  risk_rank,
  user_pseudo_id,
  CASE WHEN rank_share < 0.2 THEN 'High' WHEN rank_share < 0.5 THEN 'Medium' ELSE 'Low' END,
  ROUND(churn_probability, 4),
  IFNULL(NULLIF({_reasons_sql(obs, dataset.journey_events)}, ''),
         'No single strong signal'),
  -- stable random {HOLDOUT_PERCENT}%: the same user stays in or out of the holdout every day
  MOD(ABS(FARM_FINGERPRINT(CONCAT(user_pseudo_id, ':{HOLDOUT_SALT}'))), 100) < {HOLDOUT_PERCENT},
  '__MODEL__',
  days_since_last_active,
  active_days_{obs}d,
  ROUND(events_7d_vs_weekly_avg, 2),
  tenure_days,
  platform,
  country,
  device_category
FROM ranked""",
        [("__MODEL__", "active_model")],
    )
    return (
        _header(
            2,
            "Score every regular user and keep the list",
            "daily, e.g. 10:00, once yesterday's export has landed",
            [
                "a) Stops if yesterday's events have not arrived: scoring incomplete",
                "   data would make everyone look silent and risky.",
                "b) Finds the active model in model_registry.",
                f"c) Builds today's features from the {obs} days up to yesterday.",
                "d) Scores, ranks and bands every user, adds reasons, and marks a stable",
                f"   {HOLDOUT_PERCENT}% holdout. Today's rows are replaced, so a re-run is safe.",
                "",
                "Needs 00_setup.sql and one run of 01_retrain_monthly.sql first.",
            ],
        )
        + f"""
{_RUN_DATE_LINE.format(d=run_date)}
DECLARE events_yesterday INT64;
DECLARE active_model STRING;

-- a) Data guard
{guard}
IF events_yesterday = 0 THEN
  RAISE USING MESSAGE = FORMAT(
    'No events for %t yet: the daily export has not landed. Retry later.',
    DATE_SUB(run_date, INTERVAL 1 DAY));
END IF;

-- b) Active model
SET active_model = (SELECT model_name FROM {registry} WHERE is_active LIMIT 1);
IF active_model IS NULL THEN
  RAISE USING MESSAGE = 'No active model: run 01_retrain_monthly.sql first';
END IF;

-- c) Today's features (only the {obs} daily tables before today are read)
{build}

-- d) Score, rank, band, explain, hold out; replace today's rows
DELETE FROM {at_risk} WHERE score_date = run_date;
{insert}

SELECT risk_band, in_holdout, COUNT(*) AS users, ROUND(AVG(churn_probability), 3) AS avg_probability
FROM {at_risk}
WHERE score_date = run_date
GROUP BY risk_band, in_holdout
ORDER BY MIN(risk_rank), in_holdout;
"""
    )


